
-- ============================================================
-- REMOBIS | H1 PORTFOLIO MARGIN COMPARISON
-- ============================================================
-- Compare January-June 2025 with January-June 2026.
-- Show existing services, VAT_EXPRESS, and portfolio total.
-- Read-only.
-- ============================================================

WITH h1_data AS (

    SELECT
        CASE
            WHEN SERVICE_CODE IN ('VAT_DIESEL', 'EXCISE_DIESEL')
                THEN 'EXISTING_SERVICES'
            WHEN SERVICE_CODE = 'VAT_EXPRESS'
                THEN 'VAT_EXPRESS'
            ELSE 'OTHER_SERVICES'
        END AS SERVICE_GROUP,

        YEAR(SUBMISSION_MONTH) AS REPORT_YEAR,
        CLAIM_COUNT,
        EARNED_REVENUE_EUR,
        PROCESSING_COST_EUR,
        MARGIN_EUR

    FROM REMOBIS_CASE_STUDY.ANALYTICS.MART_MONTHLY_CLAIM_MARGIN

    WHERE MONTH(SUBMISSION_MONTH) BETWEEN 1 AND 6
      AND YEAR(SUBMISSION_MONTH) IN (2025, 2026)
),

h1_summary AS (

    SELECT
        CASE
            WHEN GROUPING(SERVICE_GROUP) = 1
                THEN 'TOTAL_PORTFOLIO'
            ELSE SERVICE_GROUP
        END AS REPORTING_GROUP,

        SUM(CASE WHEN REPORT_YEAR = 2025
            THEN MARGIN_EUR END) AS MARGIN_2025_EUR,

        SUM(CASE WHEN REPORT_YEAR = 2026
            THEN MARGIN_EUR END) AS MARGIN_2026_EUR,

        SUM(CASE WHEN REPORT_YEAR = 2026
            THEN EARNED_REVENUE_EUR END)
            AS EARNED_REVENUE_2026_EUR,

        SUM(CASE WHEN REPORT_YEAR = 2026
            THEN PROCESSING_COST_EUR END)
            AS PROCESSING_COST_2026_EUR,

        SUM(CASE WHEN REPORT_YEAR = 2026
            THEN CLAIM_COUNT END) AS CLAIM_COUNT_2026

    FROM h1_data
    GROUP BY ROLLUP(SERVICE_GROUP)
)

SELECT
    REPORTING_GROUP,
    MARGIN_2025_EUR,
    MARGIN_2026_EUR,

    MARGIN_2026_EUR - COALESCE(MARGIN_2025_EUR, 0)
        AS MARGIN_CHANGE_EUR,

    EARNED_REVENUE_2026_EUR,
    PROCESSING_COST_2026_EUR,
    CLAIM_COUNT_2026

FROM h1_summary

ORDER BY CASE REPORTING_GROUP
    WHEN 'EXISTING_SERVICES' THEN 1
    WHEN 'VAT_EXPRESS' THEN 2
    WHEN 'TOTAL_PORTFOLIO' THEN 3
    ELSE 4
END;
