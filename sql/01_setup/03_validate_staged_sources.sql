
-- REMOBIS | Stage validation
-- Purpose: Verify staged files and inspect source records.
-- Read-only validation.

-- Confirm source files exist.
LIST @REMOBIS_CASE_STUDY.RAW.STAGE_SOURCE_CSV;

-- Inspect the configured CSV parser.
DESCRIBE FILE FORMAT
    REMOBIS_CASE_STUDY.RAW.FF_REMOBIS_CSV;

-- Inspect five source claim records.
SELECT
    METADATA$FILENAME AS SOURCE_FILE,
    METADATA$FILE_ROW_NUMBER AS SOURCE_ROW_NUMBER,
    t.$1 AS TRANSACTION_ID,
    t.$2 AS TRANSACTION_DATE,
    t.$10 AS FEE_REVENUE_EUR,
    t.$11 AS PROCESSING_COST_EUR,
    t.$12 AS CLAIM_STATUS,
    t.$13 AS PROCESSING_DAYS
FROM @REMOBIS_CASE_STUDY.RAW.STAGE_SOURCE_CSV/FACT_REFUND_CLAIMS.csv
    (FILE_FORMAT => 'REMOBIS_CASE_STUDY.RAW.FF_REMOBIS_CSV') t
LIMIT 5;



-- ------------------------------------------------------------
-- Validate staged record counts against source CSV files.
-- Read-only: no data is modified.
-- ------------------------------------------------------------

SELECT 'FACT_REFUND_CLAIMS.csv' AS SOURCE_FILE,
       COUNT(*) AS STAGED_ROWS
FROM @REMOBIS_CASE_STUDY.RAW.STAGE_SOURCE_CSV/FACT_REFUND_CLAIMS.csv
    (FILE_FORMAT => 'REMOBIS_CASE_STUDY.RAW.FF_REMOBIS_CSV')

UNION ALL

SELECT 'DIM_CUSTOMER.csv', COUNT(*)
FROM @REMOBIS_CASE_STUDY.RAW.STAGE_SOURCE_CSV/DIM_CUSTOMER.csv
    (FILE_FORMAT => 'REMOBIS_CASE_STUDY.RAW.FF_REMOBIS_CSV')

UNION ALL

SELECT 'DIM_SERVICE.csv', COUNT(*)
FROM @REMOBIS_CASE_STUDY.RAW.STAGE_SOURCE_CSV/DIM_SERVICE.csv
    (FILE_FORMAT => 'REMOBIS_CASE_STUDY.RAW.FF_REMOBIS_CSV')

UNION ALL

SELECT 'DIM_COUNTRY.csv', COUNT(*)
FROM @REMOBIS_CASE_STUDY.RAW.STAGE_SOURCE_CSV/DIM_COUNTRY.csv
    (FILE_FORMAT => 'REMOBIS_CASE_STUDY.RAW.FF_REMOBIS_CSV');
