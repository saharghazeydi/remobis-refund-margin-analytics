
-- Verify RAW table schemas before ingestion.
-- Read-only validation.

SELECT
    TABLE_NAME,
    ORDINAL_POSITION,
    COLUMN_NAME,
    DATA_TYPE,
    IS_NULLABLE,
    NUMERIC_PRECISION,
    NUMERIC_SCALE
FROM REMOBIS_CASE_STUDY.INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = 'RAW'
  AND TABLE_NAME IN (
      'FACT_REFUND_CLAIMS',
      'DIM_CUSTOMER',
      'DIM_SERVICE',
      'DIM_COUNTRY'
  )
ORDER BY TABLE_NAME, ORDINAL_POSITION;
